import {
  Column,
  CreateDateColumn,
  DeleteDateColumn,
  Entity,
  Index,
  JoinColumn,
  ManyToOne,
  PrimaryGeneratedColumn,
  UpdateDateColumn,
} from 'typeorm';

import { decimalTransformer } from '../../database/decimal.transformer';

import { Loan } from './loan.entity';

export enum InstallmentStatus {
  Pending = 'pending',
  Paid = 'paid',
  Cancelled = 'cancelled',
}

@Entity('installments')
export class Installment {
  @PrimaryGeneratedColumn('uuid')
  id!: string;

  @Index()
  @Column()
  loanId!: string;

  @ManyToOne(() => Loan, { onDelete: 'CASCADE' })
  @JoinColumn({ name: 'loan_id' })
  loan!: Loan;

  @Column()
  installmentNumber!: number;

  // True only for the single "cuota inicial" (down payment) installment a
  // loan may have — always installmentNumber 1 when present. Interest-free
  // by construction (no corriente concepts are generated for it) and due
  // on a date the admin picks freely, independent of the periodic schedule
  // that governs installment 2 onward. Mora still applies if missed, so
  // this does NOT skip moratorio concepts. Replaces loans.initial_payment
  // — see migrations/1786700000000-ReplaceInitialPaymentWithDownPaymentInstallment.ts
  // for why a per-installment flag is correct here, unlike Phase 13's
  // earlier is_initial attempt.
  @Column({ default: false })
  isDownPayment!: boolean;

  @Column({
    type: 'decimal',
    precision: 12,
    scale: 2,
    transformer: decimalTransformer,
  })
  amount!: number;

  // The capital-only portion of `amount`, generated by the amortization
  // schedule (see loans/amortization/generateSchedule.ts). Nullable because
  // installments predating Phase 14 (created before this column existed —
  // amount was a single hand-entered total with no capital/interest split)
  // never had this calculated. Used by
  // docs/phases/PHASE_16_EARLY_PAYOFF.md and
  // docs/phases/PHASE_17_REFINANCING_RECALC.md to compute interest caused
  // vs. principal remaining.
  @Column({
    type: 'decimal',
    precision: 12,
    scale: 2,
    nullable: true,
    transformer: decimalTransformer,
  })
  principalPortion!: number | null;

  @Index()
  @Column({ type: 'date' })
  dueDate!: string;

  @Index()
  @Column({
    type: 'enum',
    enum: InstallmentStatus,
    default: InstallmentStatus.Pending,
  })
  status!: InstallmentStatus;

  @CreateDateColumn()
  createdAt!: Date;

  @UpdateDateColumn()
  updatedAt!: Date;

  @DeleteDateColumn()
  deletedAt!: Date | null;
}
